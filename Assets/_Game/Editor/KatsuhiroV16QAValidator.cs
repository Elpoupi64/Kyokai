    private static void ValidateReferences(
        List<string> pass,
        List<string> warnings
    )
    {
        string[] names =
        {
            "Kenjiro_TitleReference.png",
            "Yuki_TitleReference.png",
            "Takeda_TitleReference.png",
            "Kenjiro_ModelSheet.png",
            "Yuki_ModelSheet.png",
            "Takeda_ModelSheet.png"
        };

        int found = 0;

        for (int i = 0; i < names.Length; i++)
        {
            string path =
                ReferenceFolder + "/" + names[i];

            if (AssetDatabase.LoadAssetAtPath<Texture2D>(
                path
            ) != null)
            {
                found++;
            }
            else
            {
                warnings.Add(
                    "Référence personnage absente : " +
                    path
                );
            }
        }

        if (found == names.Length)
        {
            pass.Add(
                "6/6 références personnages disponibles."
            );
        }
    }

    private static void ValidateInputActions(
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        InputActionAsset asset =
            AssetDatabase.LoadAssetAtPath<InputActionAsset>(
                InputPath
            );

        if (asset == null)
        {
            blockers.Add(
                "PlayerControls.asset ne peut pas être chargé comme InputActionAsset."
            );
            return;
        }

        InputActionMap map =
            asset.FindActionMap(
                "Player",
                false
            );

        if (map == null)
        {
            blockers.Add(
                "Action Map 'Player' absent."
            );
            return;
        }

        pass.Add(
            "Action Map 'Player' disponible."
        );

        string[] actions =
        {
            "Move",
            "Jump",
            "Attack",
            "HeavyAttack",
            "Dodge",
            "SpecialAttack",
            "Ability"
        };

        for (int i = 0; i < actions.Length; i++)
        {
            InputAction action =
                map.FindAction(
                    actions[i],
                    false
                );

            if (action == null)
            {
                blockers.Add(
                    "Input Action manquante : " +
                    actions[i]
                );
            }
            else
            {
                pass.Add(
                    "Input Action : " +
                    actions[i]
                );
            }
        }

        CheckBinding(
            map,
            "Jump",
            "<Keyboard>/space",
            true,
            pass,
            warnings,
            blockers
        );

        CheckBinding(
            map,
            "Attack",
            "<Keyboard>/j",
            true,
            pass,
            warnings,
            blockers
        );

        CheckBinding(
            map,
            "HeavyAttack",
            "<Keyboard>/i",
            true,
            pass,
            warnings,
            blockers
        );

        CheckBinding(
            map,
            "Dodge",
            "<Keyboard>/leftShift",
            true,
            pass,
            warnings,
            blockers
        );

        CheckBinding(
            map,
            "SpecialAttack",
            "<Keyboard>/l",
            true,
            pass,
            warnings,
            blockers
        );

        CheckBinding(
            map,
            "Ability",
            "<Keyboard>/k",
            true,
            pass,
            warnings,
            blockers
        );

        CheckBinding(
            map,
            "Jump",
            "<Gamepad>/buttonSouth",
            false,
            pass,
            warnings,
            blockers
        );

        CheckBinding(
            map,
            "Attack",
            "<Gamepad>/buttonWest",
            false,
            pass,
            warnings,
            blockers
        );

        CheckBinding(
            map,
            "Ability",
            "<Gamepad>/buttonNorth",
            false,
            pass,
            warnings,
            blockers
        );
    }

    private static void CheckBinding(
        InputActionMap map,
        string actionName,
        string path,
        bool critical,
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        InputAction action =
            map.FindAction(
                actionName,
                false
            );

        if (action == null)
            return;

        bool found = false;

        foreach (
            InputBinding binding
            in action.bindings
        )
        {
            if (binding.path == path)
            {
                found = true;
                break;
            }
        }

        if (found)
        {
            pass.Add(
                actionName +
                " binding : " +
                path
            );
        }
        else if (critical)
        {
            blockers.Add(
                actionName +
                " : binding critique absent " +
                path
            );
        }
        else
        {
            warnings.Add(
                actionName +
                " : binding manette absent " +
                path
            );
        }
    }

    private static void ValidateAnimator(
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        AnimatorController controller =
            AssetDatabase.LoadAssetAtPath<AnimatorController>(
                AnimatorPath
            );

        if (controller == null)
        {
            blockers.Add(
                "Animator Controller réel introuvable : " +
                AnimatorPath
            );
            return;
        }

        pass.Add(
            "Animator Controller corrigé : KenjiroAnimatorController.controller."
        );

        HashSet<string> states =
            new HashSet<string>();

        for (
            int layerIndex = 0;
            layerIndex < controller.layers.Length;
            layerIndex++
        )
        {
            CollectStates(
                controller.layers[layerIndex].stateMachine,
                states
            );
        }

        string[] expectedStates =
        {
            "Idle",
            "Run",
            "Jump",
            "Fall",
            "Attack1",
            "Attack2",
            "Attack3",
            "HeavyAttack",
            "AirAttack",
            "Dodge",
            "DodgeCounter",
            "KikaiSpecial",
            "Hurt",
            "Death"
        };

        for (int i = 0; i < expectedStates.Length; i++)
        {
            if (states.Contains(
                expectedStates[i]
            ))
            {
                pass.Add(
                    "Animator state : " +
                    expectedStates[i]
                );
            }
            else
            {
                blockers.Add(
                    "Animator state manquant : " +
                    expectedStates[i]
                );
            }
        }

        HashSet<string> parameters =
            new HashSet<string>();

        foreach (
            AnimatorControllerParameter parameter
            in controller.parameters
        )
        {
            parameters.Add(
                parameter.name
            );
        }

        string[] criticalParameters =
        {
            "Speed",
            "VerticalSpeed",
            "Grounded",
            "Attack1",
            "Attack2",
            "Attack3",
            "HeavyAttack",
            "AirAttack",
            "Dodge",
            "DodgeCounter",
            "KikaiSpecial",
            "Hurt",
            "Death"
        };

        for (
            int i = 0;
            i < criticalParameters.Length;
            i++
        )
        {
            if (!parameters.Contains(
                criticalParameters[i]
            ))
            {
                blockers.Add(
                    "Animator parameter manquant : " +
                    criticalParameters[i]
                );
            }
        }

        if (controller.layers.Length == 0)
        {
            blockers.Add(
                "Animator Controller sans layer."
            );
        }
        else
        {
            pass.Add(
                "Animator possède " +
                controller.layers.Length +
                " layer(s)."
            );
        }
    }

    private static void CollectStates(
        AnimatorStateMachine stateMachine,
        HashSet<string> states
    )
    {
        if (stateMachine == null)
            return;

        ChildAnimatorState[] children =
            stateMachine.states;

        for (int i = 0; i < children.Length; i++)
        {
            if (children[i].state != null)
                states.Add(
                    children[i].state.name
                );
        }

        ChildAnimatorStateMachine[] childMachines =
            stateMachine.stateMachines;

        for (
            int i = 0;
            i < childMachines.Length;
            i++
        )
        {
            CollectStates(
                childMachines[i].stateMachine,
                states
            );
        }
    }

    private static void ValidateKenjiroPrefab(
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        GameObject prefab =
            AssetDatabase.LoadAssetAtPath<GameObject>(
                KenjiroPrefabPath
            );

        if (prefab == null)
            return;

        Transform modelRoot =
            prefab.transform.Find(
                "ModelRoot"
            );

        if (modelRoot == null)
        {
            blockers.Add(
                "Kenjiro : ModelRoot introuvable."
            );
            return;
        }

        pass.Add(
            "Kenjiro : ModelRoot présent."
        );

        if (modelRoot.Find(
            "KenjiroCharacter_v16"
        ) != null)
        {
            pass.Add(
                "KenjiroCharacter_v16 intégré."
            );
        }
        else
        {
            warnings.Add(
                "KenjiroCharacter_v16 absent du prefab. " +
                "Rebuild conseillé."
            );
        }

        if (modelRoot.Find(
            "KikaiYurei_Device"
        ) != null)
        {
            pass.Add(
                "Kikai-Yūrei présent sur Kenjiro."
            );
        }
        else
        {
            blockers.Add(
                "Kikai-Yūrei absent du prefab Kenjiro."
            );
        }

        Animator animator =
            prefab.GetComponent<Animator>();

        if (animator == null)
        {
            blockers.Add(
                "Animator absent du prefab Kenjiro."
            );
        }
        else
        {
            pass.Add(
                "Animator présent sur le prefab Kenjiro."
            );
        }

        int missingScripts =
            CountMissingScripts(
                prefab
            );

        if (missingScripts > 0)
        {
            blockers.Add(
                "Prefab Kenjiro : " +
                missingScripts +
                " script(s) manquant(s)."
            );
        }
        else
        {
            pass.Add(
                "Prefab Kenjiro : aucun script manquant."
            );
        }
    }

