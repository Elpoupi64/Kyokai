    public static ValidationResult RunPreflight(
        bool selectReport
    )
    {
        EnsureFolder("Assets/_Game");
        EnsureFolder(ReportFolder);

        List<string> pass =
            new List<string>();

        List<string> warnings =
            new List<string>();

        List<string> blockers =
            new List<string>();

        ValidateCriticalAssets(
            pass,
            warnings,
            blockers
        );

        ValidateReferences(
            pass,
            warnings
        );

        ValidateInputActions(
            pass,
            warnings,
            blockers
        );

        ValidateAnimator(
            pass,
            warnings,
            blockers
        );

        ValidateKenjiroPrefab(
            pass,
            warnings,
            blockers
        );

        ValidateDoryokuPrefab(
            pass,
            warnings,
            blockers
        );

        ValidateBuildSettings(
            pass,
            warnings,
            blockers
        );

        ValidateURPAndPostProcess(
            pass,
            warnings,
            blockers
        );

        ValidateQualityPresets(
            pass,
            warnings,
            blockers
        );

        ValidateTitleScene(
            pass,
            warnings,
            blockers
        );

        ValidateGameplayScene(
            pass,
            warnings,
            blockers
        );

        ValidateFlowContracts(
            pass,
            warnings,
            blockers
        );

        WriteReport(
            pass,
            warnings,
            blockers
        );

        AssetDatabase.Refresh();

        if (selectReport)
        {
            TextAsset reportAsset =
                AssetDatabase.LoadAssetAtPath<TextAsset>(
                    ReportPath
                );

            if (reportAsset != null)
            {
                Selection.activeObject =
                    reportAsset;

                EditorGUIUtility.PingObject(
                    reportAsset
                );
            }
        }

        ValidationResult result =
            new ValidationResult
            {
                PassCount = pass.Count,
                WarningCount = warnings.Count,
                BlockerCount = blockers.Count
            };

        string message =
            "Katsuhiro v16.1 QA — PASS: " +
            result.PassCount +
            ", WARNING: " +
            result.WarningCount +
            ", BLOCKER: " +
            result.BlockerCount +
            ".";

        if (result.BlockerCount > 0)
            Debug.LogError(message);
        else if (result.WarningCount > 0)
            Debug.LogWarning(message);
        else
            Debug.Log(message);

        return result;
    }

