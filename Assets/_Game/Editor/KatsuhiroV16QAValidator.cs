    private static void ValidateBuildSettings(
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        EditorBuildSettingsScene[] scenes =
            EditorBuildSettings.scenes;

        if (scenes.Length < 2)
        {
            blockers.Add(
                "Build Settings : moins de deux scènes."
            );
            return;
        }

        bool titleCorrect =
            scenes[0].enabled &&
            scenes[0].path == TitleScenePath;

        bool gameplayCorrect =
            scenes[1].enabled &&
            scenes[1].path == GameplayScenePath;

        if (titleCorrect &&
            gameplayCorrect)
        {
            pass.Add(
                "Build Settings : 0 TitleScreen -> 1 Foundry_Prototype."
            );
        }
        else
        {
            blockers.Add(
                "Build Settings : ordre ou activation incorrects."
            );
        }

        int extraEnabled = 0;

        for (int i = 2; i < scenes.Length; i++)
        {
            if (scenes[i].enabled)
                extraEnabled++;
        }

        if (extraEnabled > 0)
        {
            warnings.Add(
                "Build Settings : " +
                extraEnabled +
                " scène(s) supplémentaire(s) activée(s)."
            );
        }

        BuildTarget target =
            EditorUserBuildSettings.activeBuildTarget;

        if (target == BuildTarget.NoTarget)
        {
            blockers.Add(
                "Aucune plateforme de build active."
            );
        }
        else
        {
            pass.Add(
                "Plateforme active : " +
                target
            );
        }
    }

    private static void ValidateURPAndPostProcess(
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        RenderPipelineAsset pipeline =
            GraphicsSettings.currentRenderPipeline;

        if (pipeline == null)
        {
            blockers.Add(
                "Aucun Render Pipeline actif. URP est requis."
            );
        }
        else
        {
            string typeName =
                pipeline.GetType().FullName;

            if (!string.IsNullOrEmpty(typeName) &&
                typeName.IndexOf(
                    "Universal",
                    StringComparison.OrdinalIgnoreCase
                ) >= 0)
            {
                pass.Add(
                    "URP actif : " +
                    pipeline.name
                );
            }
            else
            {
                blockers.Add(
                    "Render Pipeline actif non identifié comme URP : " +
                    pipeline.GetType().Name
                );
            }
        }

        RenderPipelineAsset pcAsset =
            AssetDatabase.LoadAssetAtPath<RenderPipelineAsset>(
                PcPipelinePath
            );

        if (pcAsset != null)
        {
            pass.Add(
                "PC_RPAsset chargé."
            );

            if (pipeline != null &&
                pipeline != pcAsset)
            {
                warnings.Add(
                    "Le pipeline actif n'est pas PC_RPAsset. " +
                    "Cela peut être normal selon le Quality Level courant."
                );
            }
        }

        VolumeProfile profile =
            AssetDatabase.LoadAssetAtPath<VolumeProfile>(
                PostProcessPath
            );

        if (profile == null)
        {
            blockers.Add(
                "Volume Profile de la fonderie introuvable."
            );
            return;
        }

        pass.Add(
            "Volume Profile Foundry_Atmosphere_v14 chargé."
        );

        HashSet<string> overrides =
            new HashSet<string>();

        for (
            int i = 0;
            i < profile.components.Count;
            i++
        )
        {
            VolumeComponent component =
                profile.components[i];

            if (component != null)
                overrides.Add(
                    component.GetType().Name
                );
        }

        string[] expected =
        {
            "Bloom",
            "ColorAdjustments",
            "Vignette",
            "Tonemapping"
        };

        for (int i = 0; i < expected.Length; i++)
        {
            if (overrides.Contains(
                expected[i]
            ))
            {
                pass.Add(
                    "Post-process : " +
                    expected[i]
                );
            }
            else
            {
                warnings.Add(
                    "Post-process override absent : " +
                    expected[i]
                );
            }
        }
    }

    private static void ValidateQualityPresets(
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        string[] names =
            Enum.GetNames(
                typeof(
                    DemoQualityManager.DemoPreset
                )
            );

        HashSet<string> presets =
            new HashSet<string>(
                names
            );

        string[] expected =
        {
            "Performance",
            "Balanced",
            "Cinematic"
        };

        for (int i = 0; i < expected.Length; i++)
        {
            if (presets.Contains(
                expected[i]
            ))
            {
                pass.Add(
                    "Quality preset : " +
                    expected[i]
                );
            }
            else
            {
                blockers.Add(
                    "Quality preset manquant : " +
                    expected[i]
                );
            }
        }

        if (QualitySettings.names == null ||
            QualitySettings.names.Length == 0)
        {
            warnings.Add(
                "Unity Quality Settings ne contient aucun niveau nommé."
            );
        }
        else
        {
            pass.Add(
                "Unity Quality Settings disponibles : " +
                QualitySettings.names.Length
            );
        }
    }

    private static void ValidateTitleScene(
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        if (!File.Exists(TitleScenePath))
            return;

        Scene scene;
        bool openedHere;

        if (!TryOpenSceneForValidation(
            TitleScenePath,
            out scene,
            out openedHere
        ))
        {
            blockers.Add(
                "Impossible d'ouvrir TitleScreen pour validation."
            );
            return;
        }

        try
        {
            GameObject[] roots =
                scene.GetRootGameObjects();

            int missing =
                CountMissingScripts(
                    roots
                );

            if (missing > 0)
            {
                blockers.Add(
                    "TitleScreen : " +
                    missing +
                    " script(s) manquant(s)."
                );
            }
            else
            {
                pass.Add(
                    "TitleScreen : aucun script manquant."
                );
            }

            DemoTitleScreenController controller =
                FindInRoots<DemoTitleScreenController>(
                    roots
                );

            if (controller == null)
            {
                blockers.Add(
                    "TitleScreen : DemoTitleScreenController absent."
                );
            }
            else
            {
                SerializedObject so =
                    new SerializedObject(
                        controller
                    );

                SerializedProperty gameplayScene =
                    so.FindProperty(
                        "gameplayScene"
                    );

                if (gameplayScene != null &&
                    gameplayScene.stringValue ==
                    "Foundry_Prototype")
                {
                    pass.Add(
                        "TitleScreen -> Foundry_Prototype configuré."
                    );
                }
                else
                {
                    blockers.Add(
                        "TitleScreen : gameplayScene mal configurée."
                    );
                }

                CheckSerializedReference(
                    so,
                    "kenjiroTexture",
                    "TitleScreen : Kenjiro texture",
                    true,
                    pass,
                    warnings,
                    blockers
                );

                CheckSerializedReference(
                    so,
                    "yukiTexture",
                    "TitleScreen : Yuki texture",
                    true,
                    pass,
                    warnings,
                    blockers
                );

                CheckSerializedReference(
                    so,
                    "takedaTexture",
                    "TitleScreen : Takeda texture",
                    true,
                    pass,
                    warnings,
                    blockers
                );
            }

            if (FindInRoots<DemoQualityManager>(
                roots
            ) != null)
            {
                pass.Add(
                    "TitleScreen : DemoQualityManager présent."
                );
            }
            else
            {
                blockers.Add(
                    "TitleScreen : DemoQualityManager absent."
                );
            }

            if (FindInRoots<Camera>(
                roots
            ) != null)
            {
                pass.Add(
                    "TitleScreen : caméra présente."
                );
            }
            else
            {
                blockers.Add(
                    "TitleScreen : aucune caméra."
                );
            }
        }
        finally
        {
            CloseValidationScene(
                scene,
                openedHere
            );
        }
    }

    private static void ValidateGameplayScene(
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        if (!File.Exists(GameplayScenePath))
            return;

        Scene scene;
        bool openedHere;

        if (!TryOpenSceneForValidation(
            GameplayScenePath,
            out scene,
            out openedHere
        ))
        {
            blockers.Add(
                "Impossible d'ouvrir Foundry_Prototype pour validation."
            );
            return;
        }

        try
        {
            GameObject[] roots =
                scene.GetRootGameObjects();

            int missing =
                CountMissingScripts(
                    roots
                );

            if (missing > 0)
            {
                blockers.Add(
                    "Foundry_Prototype : " +
                    missing +
                    " script(s) manquant(s)."
                );
            }
            else
            {
                pass.Add(
                    "Foundry_Prototype : aucun script manquant."
                );
            }

            string[] requiredRoots =
            {
                "GAMEPLAY",
                "LEVEL",
                "CAMERA",
                "LIGHTING"
            };

            for (
                int i = 0;
                i < requiredRoots.Length;
                i++
            )
            {
                if (FindRoot(
                    roots,
                    requiredRoots[i]
                ) != null)
                {
                    pass.Add(
                        "Scene root : " +
                        requiredRoots[i]
                    );
                }
                else
                {
                    blockers.Add(
                        "Scene root manquant : " +
                        requiredRoots[i]
                    );
                }
            }

            PlayerInput playerInput =
                FindInRoots<PlayerInput>(
                    roots
                );

            PlayerMotor25D motor =
                FindInRoots<PlayerMotor25D>(
                    roots
                );

            PlayerHealth health =
                FindInRoots<PlayerHealth>(
                    roots
                );

            KenjiroCombatController combat =
                FindInRoots<KenjiroCombatController>(
                    roots
                );

            if (playerInput == null)
                blockers.Add("PlayerInput absent.");
            else
            {
                pass.Add("PlayerInput présent.");

                if (playerInput.actions == null)
                    blockers.Add("PlayerInput.actions non assigné.");
                else
                    pass.Add("PlayerInput.actions assigné.");

                if (playerInput.defaultActionMap == "Player")
                    pass.Add("PlayerInput defaultActionMap = Player.");
                else
                    blockers.Add("PlayerInput defaultActionMap incorrect.");
            }

            if (motor != null)
                pass.Add("PlayerMotor25D présent.");
            else
                blockers.Add("PlayerMotor25D absent.");

            if (health != null)
                pass.Add("PlayerHealth présent.");
            else
                blockers.Add("PlayerHealth absent.");

            if (combat != null)
                pass.Add("KenjiroCombatController présent.");
            else
                blockers.Add("KenjiroCombatController absent.");

            Animator animator =
                FindInRoots<Animator>(
                    roots
                );

            if (animator == null)
            {
                blockers.Add(
                    "Animator de Kenjiro absent en scène."
                );
            }
            else if (animator.runtimeAnimatorController == null)
            {
                blockers.Add(
                    "Animator de Kenjiro sans RuntimeAnimatorController."
                );
            }
            else
            {
                string path =
                    AssetDatabase.GetAssetPath(
                        animator.runtimeAnimatorController
                    );

                if (path == AnimatorPath)
                {
                    pass.Add(
                        "Animator de scène relié au bon controller."
                    );
                }
                else
                {
                    warnings.Add(
                        "Animator de scène utilise : " +
                        path
                    );
                }
            }

            KikaiWorldManager worldManager =
                FindInRoots<KikaiWorldManager>(
                    roots
                );

            if (worldManager != null)
                pass.Add("KikaiWorldManager présent.");
            else
                blockers.Add("KikaiWorldManager absent.");

            VerticalSliceDirector director =
                FindInRoots<VerticalSliceDirector>(
                    roots
                );

            if (director == null)
            {
                blockers.Add(
                    "VerticalSliceDirector absent."
                );
            }
            else
            {
                pass.Add(
                    "VerticalSliceDirector présent."
                );

                SerializedObject so =
                    new SerializedObject(
                        director
                    );

                string[] requiredReferences =
                {
                    "player",
                    "playerMotor",
                    "playerCombat",
                    "worldManager",
                    "firstEnemy",
                    "chaseSequence",
                    "boss"
                };

                for (
                    int i = 0;
                    i < requiredReferences.Length;
                    i++
                )
                {
                    CheckSerializedReference(
                        so,
                        requiredReferences[i],
                        "VerticalSliceDirector." +
                        requiredReferences[i],
                        true,
                        pass,
                        warnings,
                        blockers
                    );
                }
            }

            VerticalSliceCheckpoint[] checkpoints =
                FindAllInRoots<VerticalSliceCheckpoint>(
                    roots
                );

            if (checkpoints.Length == 0)
            {
                blockers.Add(
                    "Aucun VerticalSliceCheckpoint."
                );
            }
            else
            {
                pass.Add(
                    "Checkpoint(s) : " +
                    checkpoints.Length
                );
            }

            Doryoku3BossEncounter encounter =
                FindInRoots<Doryoku3BossEncounter>(
                    roots
                );

            if (encounter == null)
            {
                blockers.Add(
                    "Doryoku3BossEncounter absent."
                );
            }
            else
            {
                pass.Add(
                    "Doryoku3BossEncounter présent."
                );

                SerializedObject bossSO =
                    new SerializedObject(
                        encounter
                    );

                string[] bossReferences =
                {
                    "boss",
                    "player",
                    "playerMotor",
                    "playerCombat",
                    "bossCamera",
                    "bossHUD",
                    "leftGate",
                    "rightGate"
                };

                for (
                    int i = 0;
                    i < bossReferences.Length;
                    i++
                )
                {
                    CheckSerializedReference(
                        bossSO,
                        bossReferences[i],
                        "BossEncounter." +
                        bossReferences[i],
                        true,
                        pass,
                        warnings,
                        blockers
                    );
                }
            }

            if (FindInRoots<DemoPauseMenu>(
                roots
            ) != null)
                pass.Add("DemoPauseMenu présent.");
            else
                blockers.Add("DemoPauseMenu absent.");

            if (FindInRoots<DemoPerformanceHUD>(
                roots
            ) != null)
                pass.Add("DemoPerformanceHUD présent.");
            else
                warnings.Add("DemoPerformanceHUD absent.");

            if (FindInRoots<DemoQualityManager>(
                roots
            ) != null)
                pass.Add("DemoQualityManager présent en scène.");
            else
                warnings.Add(
                    "DemoQualityManager absent en scène. " +
                    "Le TitleScreen peut cependant le conserver via DontDestroyOnLoad."
                );

            Camera gameplayCamera =
                FindInRoots<Camera>(
                    roots
                );

            CameraFollow25D follow =
                FindInRoots<CameraFollow25D>(
                    roots
                );

            if (gameplayCamera == null)
            {
                blockers.Add(
                    "Caméra gameplay absente."
                );
            }
            else
            {
                pass.Add(
                    "Caméra gameplay présente."
                );

                if (gameplayCamera.allowHDR)
                    pass.Add("Caméra HDR activée.");
                else
                    warnings.Add("Caméra HDR désactivée.");
            }

            if (follow != null)
                pass.Add("CameraFollow25D présent.");
            else
                blockers.Add("CameraFollow25D absent.");

            Volume volume =
                FindInRoots<Volume>(
                    roots
                );

            if (volume == null)
            {
                warnings.Add(
                    "Global Volume absent en scène."
                );
            }
            else if (volume.sharedProfile == null)
            {
                warnings.Add(
                    "Global Volume sans profile."
                );
            }
            else
            {
                pass.Add(
                    "Global Volume relié à un profile."
                );
            }

            ValidateGameplayMarkers(
                pass,
                warnings,
                blockers
            );
        }
        finally
        {
            CloseValidationScene(
                scene,
                openedHere
            );
        }
    }

    private static void ValidateGameplayMarkers(
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        if (!File.Exists(GameplayScenePath))
            return;

        string text =
            File.ReadAllText(
                GameplayScenePath
            );

        string[] criticalMarkers =
        {
            "CombatSystem_v7",
            "CombatPolish_v8",
            "VERTICAL_SLICE_V9",
            "FoundryTruePainted_v14",
            "DemoProduction_v15",
            "DemoReleaseCandidate_v16",
            "DemoReleaseCandidate_v16_1"
        };

        for (
            int i = 0;
            i < criticalMarkers.Length;
            i++
        )
        {
            if (text.Contains(
                criticalMarkers[i]
            ))
            {
                pass.Add(
                    "Marker : " +
                    criticalMarkers[i]
                );
            }
            else if (
                criticalMarkers[i] ==
                "DemoReleaseCandidate_v16_1"
            )
            {
                warnings.Add(
                    "Marker v16.1 absent : reconstruire Foundry_Prototype."
                );
            }
            else
            {
                blockers.Add(
                    "Marker historique absent : " +
                    criticalMarkers[i]
                );
            }
        }
    }

