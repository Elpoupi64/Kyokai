    private static void CheckSourceContract(
        string path,
        string[] tokens,
        string label,
        List<string> pass,
        List<string> blockers
    )
    {
        if (!File.Exists(path))
        {
            blockers.Add(
                label +
                " : script absent " +
                path
            );
            return;
        }

        string source =
            File.ReadAllText(path);

        for (int i = 0; i < tokens.Length; i++)
        {
            if (!source.Contains(
                tokens[i]
            ))
            {
                blockers.Add(
                    label +
                    " : contrat absent '" +
                    tokens[i] +
                    "'."
                );
                return;
            }
        }

        pass.Add(
            "Flow contract : " +
            label
        );
    }

    private static bool TryOpenSceneForValidation(
        string path,
        out Scene scene,
        out bool openedHere
    )
    {
        scene =
            SceneManager.GetSceneByPath(
                path
            );

        if (scene.IsValid() &&
            scene.isLoaded)
        {
            openedHere = false;
            return true;
        }

        try
        {
            scene =
                EditorSceneManager.OpenScene(
                    path,
                    OpenSceneMode.Additive
                );

            openedHere = true;

            return
                scene.IsValid() &&
                scene.isLoaded;
        }
        catch (Exception exception)
        {
            Debug.LogException(exception);
            openedHere = false;
            return false;
        }
    }

    private static void CloseValidationScene(
        Scene scene,
        bool openedHere
    )
    {
        if (!openedHere ||
            !scene.IsValid() ||
            !scene.isLoaded)
        {
            return;
        }

        EditorSceneManager.CloseScene(
            scene,
            true
        );
    }

    private static GameObject FindRoot(
        GameObject[] roots,
        string name
    )
    {
        for (int i = 0; i < roots.Length; i++)
        {
            if (roots[i] != null &&
                roots[i].name == name)
            {
                return roots[i];
            }
        }

        return null;
    }

    private static T FindInRoots<T>(
        GameObject[] roots
    )
        where T : Component
    {
        for (int i = 0; i < roots.Length; i++)
        {
            T component =
                roots[i].GetComponentInChildren<T>(
                    true
                );

            if (component != null)
                return component;
        }

        return null;
    }

    private static T[] FindAllInRoots<T>(
        GameObject[] roots
    )
        where T : Component
    {
        List<T> list =
            new List<T>();

        for (int i = 0; i < roots.Length; i++)
        {
            T[] found =
                roots[i].GetComponentsInChildren<T>(
                    true
                );

            if (found != null &&
                found.Length > 0)
            {
                list.AddRange(found);
            }
        }

        return list.ToArray();
    }

    private static void CheckSerializedReference(
        SerializedObject serializedObject,
        string propertyName,
        string label,
        bool critical,
        List<string> pass,
        List<string> warnings,
        List<string> blockers
    )
    {
        SerializedProperty property =
            serializedObject.FindProperty(
                propertyName
            );

        if (property == null)
        {
            if (critical)
                blockers.Add(
                    label +
                    " : propriété sérialisée introuvable."
                );
            else
                warnings.Add(
                    label +
                    " : propriété sérialisée introuvable."
                );

            return;
        }

        if (property.objectReferenceValue == null)
        {
            if (critical)
                blockers.Add(
                    label +
                    " : référence non assignée."
                );
            else
                warnings.Add(
                    label +
                    " : référence non assignée."
                );
        }
        else
        {
            pass.Add(
                label +
                " assigné."
            );
        }
    }

    private static int CountMissingScripts(
        GameObject root
    )
    {
        if (root == null)
            return 0;

        int count = 0;

        Transform[] transforms =
            root.GetComponentsInChildren<Transform>(
                true
            );

        for (int i = 0; i < transforms.Length; i++)
        {
            count +=
                GameObjectUtility
                    .GetMonoBehavioursWithMissingScriptCount(
                        transforms[i].gameObject
                    );
        }

        return count;
    }

    private static int CountMissingScripts(
        GameObject[] roots
    )
    {
        int count = 0;

        for (int i = 0; i < roots.Length; i++)
            count +=
                CountMissingScripts(
                    roots[i]
                );

        return count;
    }

